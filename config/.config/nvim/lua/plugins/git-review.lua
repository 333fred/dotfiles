return {
    dir = vim.fn.stdpath("config") .. "/local/git-review.nvim",
    name = "git-review.nvim",
    lazy = false,
    dependencies = { "folke/snacks.nvim" },
    keys = {
        { "<localleader>rp", function() require("git-review").pr_diff() end, desc = "Review PR changes and comments" },
        { "<localleader>rP", function() require("git-review").since_review() end, desc = "PR changes since last review" },
        { "<localleader>pv", function() require("git-review").description() end, desc = "View/toggle PR description" },
        { "<localleader>pc", function() require("git-review").checkout_pr() end, desc = "Check out selected PR" },
        { "<localleader>rl", function() require("git-review.workflow").open_local("open") end, desc = "Review local changes" },
        { "<localleader>rb", function() require("git-review.workflow").open_local("open_branch") end, desc = "Review branch changes" },
        { "<localleader>rc", function() require("git-review.workflow").open_local("open_commits") end, desc = "Review commits" },
        { "<localleader>rs", function() require("git-review.workflow").review("start") end, desc = "Start review" },
        { "<localleader>ru", function() require("git-review.workflow").review("submit") end, desc = "Submit review" },
        { "<localleader>ra", function() require("git-review.workflow").review("approve") end, desc = "Approve PR" },
        { "<localleader>rd", function() require("git-review.workflow").review("discard") end, desc = "Discard review (confirm)" },
        { "<localleader>rm", function() require("git-review.workflow").mark_reviewed() end, desc = "Mark file reviewed" },
        { "<localleader>rt", function() require("git-review.workflow").toggle_readonly() end, desc = "Toggle review read-only" },
        { "<localleader>rq", function() require("git-review.workflow").close() end, desc = "Close review (keep comments)" },
        { "<localleader>ca", function() require("git-review.workflow").comment("add") end, mode = { "n", "x" }, desc = "Add comment/reply" },
        { "<localleader>cf", function() require("git-review.workflow").comment("file") end, desc = "Add file comment" },
        { "<localleader>co", function() require("git-review.workflow").comment("open") end, desc = "Open comment/thread" },
        { "<localleader>cl", function() require("git-review.workflow").comment("list") end, desc = "Pick comment" },
        { "<localleader>cL", function() require("git-review.workflow").comment("list_window") end, desc = "List comments in persistent window" },
        { "<localleader>ct", function() require("git-review.workflow").comment("toggle") end, desc = "Toggle comment annotations" },
        { "<localleader>ce", function() require("git-review.workflow").comment("edit") end, desc = "Edit comment" },
        { "<localleader>cd", function() require("git-review.workflow").comment("delete") end, desc = "Delete comment (confirm)" },
        { "<localleader>cr", function() require("git-review.workflow").comment("resolve") end, desc = "Resolve comment/thread" },
        { "<localleader>cR", function() require("git-review.workflow").comment("unresolve") end, desc = "Reopen comment/thread" },
        { "<localleader>cy", function() require("git-review.workflow").comment("yank") end, desc = "Yank comments as Markdown" },
        { "<localleader>cj", function() require("git-review.workflow").comment("next") end, desc = "Next comment" },
        { "<localleader>ck", function() require("git-review.workflow").comment("prev") end, desc = "Previous comment" },
    },
    config = function()
        require("git-review").setup()
        require("git-review.workflow").setup()
    end,
}
